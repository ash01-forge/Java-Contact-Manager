    private void deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteActionPerformed
        // TODO add your handling code here:
    if (tx1.getText().equals("")) {
    label3.setText("Please provide a name!!");
} else {
    try {
        FileReader f = new FileReader(ContactStorage.path());
        BufferedReader r = new BufferedReader(f);
        StringBuilder content = new StringBuilder();
        String line;

        boolean contactFound = false; 
        while ((line = r.readLine()) != null) {
            String[] part = line.split("-");
            if (tx1.getText().equals(part[0])) {
                contactFound = true; 
                tx2.setText("This Contact has been deleted");
                continue; 
            }
            content.append(line).append("\n");
        }

        if (!contactFound) {
            tx2.setText("Name Not Found!!");
        }

        r.close();

       
        FileWriter writer = new FileWriter(ContactStorage.path());
        writer.write(content.toString());
        writer.close();

    } catch (Exception a) {
        a.printStackTrace();
    }
    }





        
    }//GEN-LAST:event_deleteActionPerformed

