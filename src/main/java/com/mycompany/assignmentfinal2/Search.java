    private void searchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchActionPerformed
        // TODO add your handling code here:
        if(tx1.getText().equals("")){
            label2.setText("Please provide a name!!");
        }
        else{
           try{
            FileReader f= new FileReader(ContactStorage.path());
            BufferedReader r= new BufferedReader(f);
            String line;
            while((line=r.readLine())!=null){
                String[] part=line.split("-");
                if(tx1.getText().equals(part[0])){
                    tx2.setText("Name :"+part[0]+"\n"+"Phone :"+part[1]+"\n"+"Email :"+part[2]+"\n");
                    break;
                }

            }
            if(line==null){
                tx2.setText("Not Found!!");
            }
            r.close();

        }
        catch(Exception a){
            a.printStackTrace();

        }  
        }
    }//GEN-LAST:event_searchActionPerformed

